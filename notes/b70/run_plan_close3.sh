#!/usr/bin/env bash
# The missing rung. plan_decode_cost.slab_advice() refuses to interpolate a sign between E=16 (co-scheduling
# loses) and E=512 (it wins 9-16 %), and the operating point that LIVE ROUTING actually produces at R=2048 is
# ~124 eligible experts per launch - squarely in between. So the dispatch decision D17 rests on is unmeasured,
# and this fills it: probe_gemm variant A (sequential bucket launches, the shipped shape) vs variant B (one
# launch, slab index fastest-varying, co-resident) at E=128 and E=256, the two rungs that bracket it.
#
# Also settles whether "device full => no re-use gain" (the fill predictor) or "weights >> L2 => re-use" is the
# operative condition: at E=128/256 with 1.13 MiB experts the weights are 2x128x0.38 MiB ~ 96 MiB = 4x L2, while
# items/launch is 40*2*2*128 ~ 20480 (full). The two predictors say opposite things; the measurement arbitrates.
set +e
cd "$(dirname "$0")/../.." || exit 1
ROOT=$PWD
source /opt/intel/oneapi/setvars.sh >/dev/null 2>&1
source notes/env.sh >/dev/null 2>&1
MD=/home/treo/projects/vendor/tabbyAPI/models
B=notes/b70
Q=/tmp/queue
say() { echo "### $* $(date +%H:%M:%S)" | tee -a $Q/progress.txt; }

while pgrep -f "b70/[r]un_plan_close2.sh" >/dev/null; do sleep 30; done
say "QUEUE3 START"
OUT=$B/out_probe_gemm_midE.txt
{ echo "# mid-E co-scheduling rung: probe_gemm A (sequential bucket launches) vs B (co-resident slabs, one launch)"
  echo "# model Qwen3.8@2.05bpw layer 12, WARM_S=3, ks=2; B/A < 1 means co-scheduling wins"
  echo "# generated by notes/b70/run_plan_close3.sh"; } > $OUT
for spec in "128 64" "256 64" "128 32" "256 32"; do
  set -- $spec; E=$1; R=$2
  CD=/tmp/midE_e${E}_r${R}
  say "dump E=$E rows=$R"
  timeout 1200 python3 $B/dump_gemv_case.py $CD $E $R 12 --ckpt "$MD/Qwen3.8-Flash-Next-exl3-2.05bpw_h4_ng4" \
      > $Q/dump_midE_${E}_${R}.log 2>&1
  if [ ! -d "$CD" ]; then echo "  dump FAILED for E=$E rows=$R (see $Q/dump_midE_${E}_${R}.log)" | tee -a $OUT; continue; fi
  for m in A B; do
    say "mode $m E=$E rows=$R"
    echo "== GEMM_MODE=$m E=$E rows=$R" >> $OUT
    GEMM_MODE=$m WARM_S=3 timeout 900 "$ROOT/$B/probe_gemm" $CD 500 $R 2 >> $OUT 2>&1
  done
done
say "QUEUE3 COMPLETE -> $OUT"